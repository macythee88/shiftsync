-- Employee availability change notifications for managers.
-- Employees can create/read only their own notification records; managers can read/update all.
create table if not exists public.manager_notifications (
  id bigint generated by default as identity primary key,
  emp_id text not null references public.emp_data(emp_id) on delete cascade,
  actor_user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  work_date date not null,
  action text not null check (action in ('submitted','updated','cancelled')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists manager_notifications_created_at_idx
  on public.manager_notifications (created_at desc);
create index if not exists manager_notifications_emp_date_idx
  on public.manager_notifications (emp_id, work_date);
alter table public.manager_notifications enable row level security;
drop policy if exists manager_notifications_select on public.manager_notifications;
drop policy if exists manager_notifications_insert on public.manager_notifications;
drop policy if exists manager_notifications_update on public.manager_notifications;
create policy manager_notifications_select on public.manager_notifications
  for select using (
    is_mgr() or exists (
      select 1 from public.emp_data e
      where e.emp_id = manager_notifications.emp_id and e.user_id = auth.uid()
    )
  );
create policy manager_notifications_insert on public.manager_notifications
  for insert with check (
    actor_user_id = auth.uid()
    and exists (
      select 1 from public.emp_data e
      where e.emp_id = manager_notifications.emp_id and e.user_id = auth.uid()
    )
  );
create policy manager_notifications_update on public.manager_notifications
  for update using (is_mgr()) with check (is_mgr());
